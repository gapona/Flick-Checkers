/**
 * Asset keys and atlas frame names — the single place the strings `scripts/make-atlas.mjs` writes
 * and the strings the game reads are allowed to meet. A frame renamed in the generator without a
 * change here is a silently missing sprite, so both sides point at this file.
 *
 * Loaded by `scenes/Preloader.ts`; regenerate the files themselves with `npm run assets`.
 *
 * **State of the art as of S1** (CHAPAEV-PLAN.md §10): the committed atlas and sound set are the
 * ones carried over from the draughts project, and they are the draughts SHAPES — 1.6:1 ellipses
 * with a crown's headroom reserved above them, tile frames drawn for a checkerboard. S12b
 * regenerates them for this game (round discs, a separate shadow frame, a gloss highlight, the
 * per-branch "floor" sprites of §4) and S10 regenerates the audio for §9's cue list. Everything
 * below is therefore correct about what is ON DISK today, not about what the finished game ships.
 */

export const ATLAS_KEY = 'game'

/**
 * The themed sets. Each one is the board squares, the pieces and the background as a single
 * package — never mixed and matched, so a player cannot assemble a combination nobody looked at.
 *
 * An id is PERMANENT: it is stored in `SaveState.skins` and is also the shop item's id
 * (`src/game/economy.ts`), so renaming one both orphans everyone who bought it and silently
 * un-equips it. `'default'` is the free set every save starts on.
 */
export const SKIN_IDS = ['default', 'emerald', 'sunset', 'frost', 'sand', 'ink', 'crimson', 'plum', 'moss', 'slate'] as const
export type SkinId = (typeof SKIN_IDS)[number]
export const DEFAULT_SKIN: SkinId = 'default'

/** Narrows an arbitrary string — a value out of the save file, which may predate a rename or have
 * been hand-edited — to a skin this build actually ships art for. */
export function isSkinId(value: string): value is SkinId {
  return (SKIN_IDS as readonly string[]).includes(value)
}

/** Texture key of a skin's background. One image per skin, kept out of the atlas because it is a
 * full-screen picture, not a sprite. */
export function backgroundKey(skin: SkinId): string {
  return `bg-${skin}`
}

/** Path under `assets/`, for `Preloader`'s `this.load.image()`. */
export function backgroundPath(skin: SkinId): string {
  return `bg/${skin}.webp`
}

