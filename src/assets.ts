/**
 * The sound set, generated by `scripts/make-audio.mjs` (`npm run audio`) — same "one place the
 * generator's strings and the game's strings meet" rule as the atlas frames. Provenance for every
 * file is in `AUDIO-SOURCES.md`; `scripts/check-bundle.mjs` FAILS the build if a shipped audio
 * file has no row there.
 *
 * Keys and file stems are the same string, so `Preloader` loads them in one loop — which is why
 * the S1 cue names below are still the draughts ones: renaming a key here without regenerating the
 * files would be a build-green, silence-in-game bug. The Chapaev role each cue plays today is in
 * its comment, and S10 (§9) renames key and file together:
 *
 *   move -> shot, capture -> impact (volume/pitch from collision energy), promote -> knockout,
 *   plus a new combo cue with a rising pitch.
 */
export const SFX = {
  /** Every button in the kit, via `ui/theme.ts`'s `setPressSound()`. */
  ui: 'ui',
  /** The flick releasing — one shot fired. */
  move: 'move',
  /** Disc against disc. §9 makes this the game's main sound, scaled by impact energy. */
  capture: 'capture',
  /** A disc leaving the board. */
  promote: 'promote',
  win: 'win',
  lose: 'lose',
} as const

export type SfxKey = (typeof SFX)[keyof typeof SFX]

export const MUSIC_KEY = 'music'

/** Every audio key this game loads, in load order. */
export const AUDIO_KEYS: readonly string[] = [...Object.values(SFX), MUSIC_KEY]

/** Path under `assets/`, for `Preloader`'s `this.load.audio()`. */
export function audioPath(key: string): string {
  return `audio/${key}.ogg`
}


